#!/usr/bin/env python3
"""Flatten every result file into data/derived/results/numbers.md (one `file: key.path = value` line each),
so each number quoted in AUDIT.md can be traced to the script that produced it."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

SOURCES = {
    "price_boundaries.json": "11_prices_boundaries.py",
    "splice.json": "14_prices_splice.py",
    "prices_rc_validation.json": "16_prices_release_validate.py",
    "news_audit.json": "21_news_audit.py",
    "timestamps.json": "22_news_timestamps.py",
    "news_dates.json": "25_news_dates.py",
    "prices_quality.json": "17_prices_quality.py",
    "impact.json": "30_impact_experiment.py",
}


def flat(x, prefix=""):
    if isinstance(x, dict):
        for k, v in x.items():
            yield from flat(v, f"{prefix}.{k}" if prefix else str(k))
    elif isinstance(x, list) and x and all(isinstance(e, dict) for e in x):
        for i, e in enumerate(x):
            yield from flat(e, f"{prefix}[{i}]")
    else:
        yield prefix, x


def main():
    lines = ["# Numbers behind AUDIT.md (generated by scripts/50_numbers.py; do not edit)", ""]
    files = dict(SOURCES)
    files["../release/prices_rc_summary.json"] = "15_prices_release.py"
    files["../release/news_patch_summary.json"] = "23_news_release.py"
    for name, script in files.items():
        p = (common.RESULTS / name).resolve()
        if not p.exists():
            lines.append(f"## {name}: MISSING (run {script})")
            continue
        lines.append(f"## {p.name}  (scripts/{script})")
        d = json.loads(p.read_text())
        if name == "impact.json":
            for r in d.get("table", []):
                key = f"{r['subset']}|{r['alignment']}|{r['target']}"
                vals = ", ".join(f"{m}={r[m]:.4f} {[round(c, 4) for c in r[m + '_ci']]}" for m in ("accuracy", "ic", "sharpe"))
                diff = ", ".join(f"d{m}={r[m + '_minus_noleak']:.4f} {[round(c, 4) for c in r[m + '_minus_noleak_ci']]}"
                                 for m in ("accuracy", "ic", "sharpe") if m + "_minus_noleak" in r)
                lines.append(f"- {key}: n_obs={r['n_obs']}, days={r['n_days']}, {vals}; {diff}")
            d = {k: v for k, v in d.items() if k != "table"}
        for k, v in flat(d):
            lines.append(f"- {k} = {v}")
        lines.append("")
    out = common.RESULTS / "numbers.md"
    out.write_text("\n".join(lines) + "\n")
    print(out, len(lines), "lines")


if __name__ == "__main__":
    main()
